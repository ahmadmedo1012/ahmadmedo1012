#!/usr/bin/env node
/**
 * LIVE SVG ENGINE — ahmadmedo1012 profile
 * ----------------------------------------
 * Pulls real data from the GitHub API and generates fully-animated SVG
 * assets (SMIL — survives GitHub camo proxying) in the profile identity:
 * ink #0D1017 / amber #E2A93B / paper #F2EFE6 — no gradients.
 *
 * Outputs:
 *   assets/stats-live.svg     — profile counters (odometer digits)
 *   assets/heatmap-live.svg   — 365-day contribution heatmap + scan
 *   assets/projects-live.svg  — project cards w/ live stars & forks
 *   assets/languages-live.svg — top languages, animated bars
 *
 * Design contract (IDENTITY.md):
 *   - Every number is LIVE — never hand-written.
 *   - Every asset MOVES with purpose.
 *   - Graceful degradation: base state = final state (correct at t=0),
 *     animations reveal motion on top. SMIL only, no JS.
 *
 * Env:
 *   GITHUB_TOKEN  optional — raises rate limits, enables GraphQL
 *   GITHUB_USER   default ahmadmedo1012
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const USER = process.env.GITHUB_USER || 'ahmadmedo1012';
const TOKEN = process.env.GITHUB_TOKEN || '';
const H = { Accept: 'application/vnd.github+json', 'User-Agent': 'live-svg-engine' };
if (TOKEN) H.Authorization = `Bearer ${TOKEN}`;

/* ---------- identity palette ---------- */
const INK = '#0D1017', CARD = '#11151E', CARD2 = '#161D29', LINE = '#2A3242',
  AMBER = '#E2A93B', AMBER_DIM = '#8A6420', PAPER = '#F2EFE6', MUTE = '#C7CEDB', DIM = '#7E8798';
const MONO = "Cascadia Code, SF Mono, Menlo, Consolas, DejaVu Sans Mono, monospace";
const AR = "Segoe UI, Tahoma, Noto Sans Arabic, Geeza Pro, sans-serif";

const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/* ---------- odometer: slot-machine digits that roll into place ----------
   Base transform = final digit (correct without SMIL / at t=0 screenshots).
   Animation rolls 0 -> target, freezes. */
let uid = 0;
function odo(str, cx, y, o = {}) {
  const size = o.size ?? 34, color = o.color ?? AMBER,
    begin = o.begin ?? 0.45, step = o.step ?? 0.11;
  const w = size * 0.64, rowH = size * 1.3;
  const digits = String(str).split('');
  const x0 = cx - ((digits.length - 1) * w) / 2;
  let defs = '', body = '';
  digits.forEach((d, i) => {
    const t = parseInt(d, 10) || 0;
    const id = `od${uid++}`, dx = x0 + i * w;
    defs += `<clipPath id="${id}"><rect x="${(dx - w / 2 - 0.8).toFixed(1)}" y="${(y - size * 0.82).toFixed(1)}" width="${(w + 1.6).toFixed(1)}" height="${(size * 1.04).toFixed(1)}"/></clipPath>`;
    let rows = '';
    for (let n = 0; n <= 9; n++) {
      rows += `<text x="${dx.toFixed(1)}" y="${(y + n * rowH).toFixed(1)}" font-family="${MONO}" font-size="${size}" font-weight="700" fill="${color}" text-anchor="middle">${n}</text>`;
    }
    const dur = (0.7 + t * 0.1 + i * 0.06).toFixed(2);
    body += `<g clip-path="url(#${id})"><g transform="translate(0 ${(-t * rowH).toFixed(1)})">${rows}` +
      `<animateTransform attributeName="transform" type="translate" from="0 0" to="0 ${(-t * rowH).toFixed(1)}" begin="${(begin + i * step).toFixed(2)}s" dur="${dur}s" calcMode="spline" keySplines="0.22 0.9 0.28 1" keyTimes="0;1" fill="freeze"/></g></g>`;
  });
  return { defs, body };
}

function doc(W, Hh, defs, body, label) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${Hh}" viewBox="0 0 ${W} ${Hh}" role="img" aria-label="${esc(label)}">
<title>${esc(label)}</title>
<!-- GENERATED by scripts/generate-live-svg.mjs · live GitHub data · auto-synced every 6h · do not edit manually -->
<defs>${defs}</defs>
<rect width="${W}" height="${Hh}" fill="${INK}"/>
${body}
</svg>`;
}

const save = (file, svg) => { writeFileSync(join(ROOT, file), svg); console.log(`  wrote ${file} (${(svg.length / 1024).toFixed(1)} KB)`); };

/* ============================ DATA ============================ */
async function j(url, opts = {}) {
  const r = await fetch(url, { ...opts, headers: { ...H, ...(opts.headers || {}) } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}
async function graphql() {
  const query = `query($u:String!){ user(login:$u){
    followers{totalCount}
    contributionsCollection{ contributionCalendar{ totalContributions weeks{ contributionDays{ date contributionCount } } } }
    repositories(first:100,isFork:false){ totalCount nodes{
      name description stargazerCount forkCount pushedAt
      primaryLanguage{name}
      languages(first:8,orderBy:{field:SIZE,direction:DESC}){edges{size node{name}}}
    } }
  } }`;
  const data = await j('https://api.github.com/graphql', {
    method: 'POST', body: JSON.stringify({ query, variables: { u: USER } }),
    headers: { 'Content-Type': 'application/json' },
  });
  if (data.errors) throw new Error('graphql: ' + JSON.stringify(data.errors).slice(0, 120));
  return data.data.user;
}
async function restFallback() {
  const user = await j(`https://api.github.com/users/${USER}`);
  let repos = [], page = 1;
  while (page <= 3) {
    const b = await j(`https://api.github.com/users/${USER}/repos?per_page=100&page=${page}`);
    repos = repos.concat(b); if (b.length < 100) break; page++;
  }
  repos = repos.filter(r => !r.fork);
  const langBytes = {};
  const recent = [...repos].sort((a, b) => new Date(b.pushed_at) - new Date(a.pushed_at)).slice(0, 30);
  for (const r of recent) {
    try { const L = await j(`https://api.github.com/repos/${USER}/${r.name}/languages`);
      for (const [k, v] of Object.entries(L)) langBytes[k] = (langBytes[k] || 0) + v;
    } catch { /* per-repo language is best-effort */ }
  }
  return { user, repos, langBytes };
}

