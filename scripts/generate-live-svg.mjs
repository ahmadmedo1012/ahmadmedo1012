let uid = 0;

/* ---------- odometer: slot-machine digits that roll into place ----------
   Base transform = final digit (correct without SMIL / at t=0 screenshots).
   Animation rolls 0 -> target, freezes. */
function odo(str, cx, y, t, o = {}) {
  const size = o.size ?? 34, color = o.color ?? t.amberDeep,
    begin = o.begin ?? 0.45, step = o.step ?? 0.11;
  const w = size * 0.64, rowH = size * 1.3;
  const digits = String(str).split('');
  const x0 = cx - ((digits.length - 1) * w) / 2;
  let defs = '', body = '';
  digits.forEach((d, i) => {
    const n = parseInt(d, 10) || 0;
    const id = `od${uid++}`, dx = x0 + i * w;
    defs += `<clipPath id="${id}"><rect x="${(dx - w / 2 - 0.8).toFixed(1)}" y="${(y - size * 0.82).toFixed(1)}" width="${(w + 1.6).toFixed(1)}" height="${(size * 1.04).toFixed(1)}"/></clipPath>`;
    let rows = '';
    for (let n2 = 0; n2 <= 9; n2++) {
      rows += `<text x="${dx.toFixed(1)}" y="${(y + n2 * rowH).toFixed(1)}" font-family="${MONO}" font-size="${size}" font-weight="700" fill="${color}" text-anchor="middle">${n2}</text>`;
    }
    const dur = (0.7 + n * 0.1 + i * 0.06).toFixed(2);
    body += `<g clip-path="url(#${id})"><g transform="translate(0 ${(-n * rowH).toFixed(1)})">${rows}` +
      `<animateTransform attributeName="transform" type="translate" from="0 0" to="0 ${(-n * rowH).toFixed(1)}" begin="${(begin + i * step).toFixed(2)}s" dur="${dur}s" calcMode="spline" keySplines="0.22 0.9 0.28 1" keyTimes="0;1" fill="freeze"/></g></g>`;
  });
  return { defs, body };
}

/* ---------- shared panel header: title right (ar) · live chip left ---------- */
function panelHeader(t, title, left) {
  return `<text x="1176" y="36" text-anchor="end" font-family="${AR}" font-size="19" font-weight="700" fill="${t.ink}">${title}</text>
  <circle cx="28" cy="32" r="4" fill="${t.amber}"><animate attributeName="opacity" values="1;.2;1" dur="1.8s" repeatCount="indefinite"/></circle>
  <text x="42" y="36" font-family="${MONO}" font-size="12.5" letter-spacing="0.5" fill="${t.dim}" direction="ltr">${left}</text>`;
}

function doc(W, Hh, defs, body, label, t) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${Hh}" viewBox="0 0 ${W} ${Hh}" role="img" aria-label="${esc(label)}">
<title>${esc(label)}</title>
<!-- GENERATED by scripts/generate-live-svg.mjs · live GitHub data · dual-theme · auto-synced every 6h · do not edit manually -->
<defs>${defs}
<filter id="lift" x="-6%" y="-6%" width="112%" height="116%"><feDropShadow dx="0" dy="4" stdDeviation="7" flood-color="${t.shadow}"/></filter></defs>
${body}
</svg>`;
}

