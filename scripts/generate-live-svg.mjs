      body += `<text x="565" y="${base}" text-anchor="end" font-family="${MONO}" font-size="10.5" letter-spacing="1" fill="${t.mute}">RECENT</text>`;
      body += `<circle cx="579" cy="${base - 4}" r="3.5" fill="${t.mute}"/>`;
