/* ============================ MAIN ============================ */
async function main() {
  console.log(`live-svg-engine → @${USER}`);
  let g = null;
  try { g = await graphql(); console.log('  data source: GraphQL'); }
  catch (e) { console.error('  GraphQL unavailable → REST fallback:', e.message); }

  let m = {};
  if (g) {
    const nodes = g.repositories.nodes || [];
    m.stars = nodes.reduce((s, r) => s + r.stargazerCount, 0);
    m.forks = nodes.reduce((s, r) => s + r.forkCount, 0);
    m.followers = g.followers.totalCount;
    m.repos = nodes.length;
    const cal = g.contributionsCollection.contributionCalendar;
    m.contributions = cal.totalContributions;
    m.weeks = cal.weeks;
    m.weeks12 = cal.weeks.slice(-12).map(w => w.contributionDays.reduce((s, d) => s + d.contributionCount, 0));
    /* current streak: consecutive contributing days ending today (or yesterday) */
    const days = cal.weeks.flatMap(w => w.contributionDays.map(d => [d.date, d.contributionCount]));
    const byDate = new Map(days);
    const fmt = d => d.toISOString().slice(0, 10);
    const t0 = new Date();
    if (!(byDate.get(fmt(t0)) > 0)) t0.setDate(t0.getDate() - 1);
    let streak = 0;
    while (byDate.get(fmt(t0)) > 0) { streak++; t0.setDate(t0.getDate() - 1); }
    m.streak = streak;
    m.reposList = nodes.map(r => ({
      name: r.name, desc: r.description, stars: r.stargazerCount, forks: r.forkCount,
      lang: r.primaryLanguage?.name || '', pushed: r.pushedAt,
    }));
    const lb = {};
    nodes.forEach(r => (r.languages?.edges || []).forEach(e => { lb[e.node.name] = (lb[e.node.name] || 0) + e.size; }));
    m.langBytes = lb;
  } else {
    const { user, repos, langBytes } = await restFallback();
    m.stars = repos.reduce((s, r) => s + r.stargazers_count, 0);
    m.forks = repos.reduce((s, r) => s + r.forks_count, 0);
    m.followers = user.followers;
    m.repos = repos.length;
    m.reposList = repos.map(r => ({
      name: r.name, desc: r.description, stars: r.stargazers_count, forks: r.forks_count,
      lang: r.language || '', pushed: r.pushed_at,
    }));
    m.langBytes = langBytes;
  }
  m.date = new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC';

  const langs = Object.entries(m.langBytes).filter(([n]) => n !== 'Dockerfile')
    .sort((a, b) => b[1] - a[1]).slice(0, 5).map(([name, bytes]) => ({ name, bytes }));
  const total = langs.reduce((s, l) => s + l.bytes, 0) || 1;
  langs.forEach(l => { l.pct = (l.bytes / total * 100).toFixed(1); });

  /* the 8 flagship products in README order; anything else appended by stars */
  const FLAG = ['ulara', 'madarek', 'SubNation2', 'SmartBot', 'Smart-Menu', 'Smart-Order', 'Smart-Link', 'lyosint'];
  m.reposList.forEach(r => { if (!r.desc) r.desc = ''; });
  const byName = new Map(m.reposList.map(r => [r.name.toLowerCase(), r]));
  const flagged = FLAG.map(n => byName.get(n.toLowerCase())).filter(Boolean);
  const extra = m.reposList
    .filter(r => !flagged.includes(r))
    .sort((a, b) => (b.stars - a.stars) || (new Date(b.pushed) - new Date(a.pushed)))
    .slice(0, Math.max(0, 8 - flagged.length));
  const proj = [...flagged, ...extra]
    .sort((a, b) => (b.stars - a.stars) || (new Date(b.pushed) - new Date(a.pushed)));

  console.log('  metrics:', JSON.stringify({ stars: m.stars, forks: m.forks, followers: m.followers, repos: m.repos, contributions: m.contributions, streak: m.streak }));

  for (const t of Object.values(THEMES)) {
    console.log(`  theme: ${t.name}`);
    const s = statsSVG(m, t); save(`assets/stats-live-${t.name}.svg`, doc(s.W, s.H, s.defs, s.body, s.label, t));
    if (m.weeks) { const h = heatmapSVG(m, t); save(`assets/heatmap-live-${t.name}.svg`, doc(h.W, h.H, h.defs, h.body, h.label, t)); }
    const p = projectsSVG(proj, t); if (p) save(`assets/projects-live-${t.name}.svg`, doc(p.W, p.H, p.defs, p.body, p.label, t));
    if (langs.length) { const l = languagesSVG(langs, t); save(`assets/languages-live-${t.name}.svg`, doc(l.W, l.H, l.defs, l.body, l.label, t)); }
  }
  console.log('done.');
}
main().catch(e => { console.error(e); process.exit(1); });
